"""单轮代码问答的 prompt。

**引用不由模型生成。** 模型只写回答正文，引用由代码从检索块的元数据组装——这是 R13 从
「要求」变成「保证」的机制。让模型自己写路径行号会引入幻觉路径，而问答的引用无法像报告
那样事后校验（报告有 U8 的校验层，问答是即时返回的）。

所以 prompt 让模型用「片段 N」的编号指代来源，代码再把编号映射回真实的路径与行号。模型
说不出它没看到的片段编号，也编不出不存在的路径。
"""

from __future__ import annotations

SYSTEM_PROMPT = """你在回答关于一个代码仓库的问题。下面会给你若干代码片段，每个片段有编号。

回答要求：
- 只依据给出的片段回答。片段里没有的内容不要推测，也不要用你对同类框架的一般印象补充。
- 提到某个结论时，用「片段 N」指明依据，例如「入口在片段 1 的 create_app 函数」。系统会把编号替换成真实的文件路径与行号。
- 不要自己写文件路径或行号——写了也会被忽略，因为引用由系统从片段元数据生成。
- 若给出的片段不足以回答问题，直接说明哪部分无法从这些片段确定，不要用无关片段凑一个答案。

回答用中文，简洁直接。符号名、路径、框架名保留原文。"""


def build_question_message(question: str, snippets: list[tuple[int, str, str]]) -> str:
    """组装问题与片段。

    snippets 的每项是 (编号, 定位描述, 代码内容)。定位描述给模型看的是符号名而非路径——
    路径由系统在引用里给出，让模型看到路径反而会诱使它自己写路径（prompt 已禁止，但少一个
    诱因更可靠）。
    """
    parts = [f"问题：{question}", "", "代码片段："]
    for index, label, content in snippets:
        parts.append(f"\n--- 片段 {index}（{label}）---\n{content}")
    return "\n".join(parts)
